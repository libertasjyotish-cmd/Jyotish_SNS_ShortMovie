const MONTHS = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];

/** Attach the preposition لِـ: "ال…" becomes "لل…". */
const lam = (text: string) => (text.startsWith('ال') ? `ل${text.slice(1)}` : `ل${text}`);

export const AR: LanguagePack = {
  worries: WORRIES,
  field: FIELD,
  write({ moon, chosen, house, period, day, worry: [hook, reason, use] }) {
    const planet = PLANET[chosen.planet];
    const fem = FEMININE.has(chosen.planet);
    const v = (masc: string, femVerb: string) => (fem ? femVerb : masc);
    const field = FIELD[house];
    const from = `من برجك القمري ${sign(moon)}`;
    const lead = `في علم التنجيم الفيدي، من ${period}،`;
    let opening: string;
    let cause: string;
    if (chosen.ingress && day) {
      opening = `${lead} ${v('ينتقل', 'تنتقل')} ${planet} إلى ${sign(chosen.ingress.sign)}، البيت ${house} ${from}، يوم ${day.date} ${MONTHS[day.month]}.`;
      cause = `${v('يدخل', 'تدخل')} مجال ${field}`;
    } else if (chosen.retrograde && !isNode(chosen.planet)) {
      opening = `${lead} ${planet} في حالة تراجع داخل ${sign(chosen.sign)}، البيت ${chosen.house} ${from}.`;
      cause = `في حالة تراجع ${v('ويدعوك', 'وتدعوك')} إلى إعادة النظر في ${field}`;
    } else {
      opening = `${lead} ${planet} في ${sign(chosen.sign)}، البيت ${chosen.house} ${from}.`;
      cause =
        chosen.planet === 'Rahu'
          ? `يزيد تركيزك على ${field}`
          : chosen.planet === 'Ketu'
            ? `يُبعد قلبك عن ${field}`
            : `${v('يؤثر', 'تؤثر')} بقوة في ${field}`;
    }
    return {
      hook: `${sign(moon)}، ${hook}`,
      body: `${opening} إذا كنت ${reason}، فذلك لأن ${NATURE[chosen.planet]} ${cause}. هذا وقت مناسب ${lam(use)}`,
    };
  },
};
